// SPEC-PARAMETER-REF — the Overview's own fields are prose, and prose carries references.
//
// THE GAP THESE PIN. `OverviewBody` rendered `prose.text`, the PLAIN projection of the segments, and a
// `ParameterRef` projects to nothing there by design (`loader.py::_plain` — *the measurement period* is
// the sentence minus the year, not a hole). So the one field that cites the measurement period rendered
// it with the year deleted and no mark of any kind: the reference did not degrade, it disappeared. Every
// criterion below it resolved the same reference correctly, which is exactly the two-answers-in-one-
