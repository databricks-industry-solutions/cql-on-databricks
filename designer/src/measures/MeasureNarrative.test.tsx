/** The reference sets for the fixture closure, generated by the real extractor. */
const REFSETS = Object.values(refsets) as unknown as ReferenceSet[];

const ref = (name: string) => ({ type: "ExpressionRef", name, annotation: [] });
const literal = (value: string) => ({
  type: "Literal", valueType: "{urn:hl7-org:elm-types:r1}Boolean", value, annotation: [],
});
const system = (t: string) => ({ type: "NamedTypeSpecifier", name: `{urn:hl7-org:elm-types:r1}${t}`, annotation: [] });

interface Def {
  name: string;
  /** The CQL body, as one line — what the section discloses as its code. */
  body: string;
  expression: unknown;
  /** Operand name → System type. Present makes it a FunctionDef; `{}` is a zero-argument function. */
  operands?: Record<string, string>;
  /** CQL annotation tags, as the translator emits them into `annotation[].t[]` with
   *  `EnableAnnotations` — the authored half of a define's narration (`SPEC-NARRATIVE-TAGS`). */
  tags?: Record<string, string>;
}

/** Emit a library as BOTH its CQL source and its ELM, with locators that line up, so each body is
 *  really sliced out of source rather than asserted into place. */
function library(name: string, defs: Def[]): SpecLibraryInput {
  const lines = [`library ${name} version '1.0.0'`, "", "using FHIR version '4.0.1'", ""];
  const statements: Record<string, unknown>[] = [];
  for (const d of defs) {
    const operands = d.operands
      ? Object.entries(d.operands).map(([n, t]) => ({ name: n, operandTypeSpecifier: system(t) }))
      : null;
    const params = d.operands ? Object.entries(d.operands).map(([n, t]) => `${n} ${t}`).join(", ") : "";
    const header = operands ? `define function "${d.name}"(${params}):` : `define "${d.name}":`;
    const start = lines.length + 1;
    lines.push(header, `  ${d.body}`, "");
    statements.push({
      locator: `${start}:1-${start + 1}:${(`  ${d.body}`).length}`,
      name: d.name,
      context: "Patient",
      accessLevel: "Public",
      annotation: [{
        type: "Annotation", s: { r: "1", s: [{ value: [header] }] },
        // The `a:s` source narrative rides alongside the tags in real output, so it does here too.
        ...(d.tags ? { t: Object.entries(d.tags).map(([name, value]) => ({ name, value })) } : {}),
      }],
      ...(operands ? { type: "FunctionDef", operand: operands } : {}),
      expression: d.expression,
    });
  }
  const elm = {
    library: {
      identifier: { id: name, version: "1.0.0" },
      usings: { def: [{ localIdentifier: "FHIR", uri: "http://hl7.org/fhir", version: "4.0.1" }] },
      statements: { def: statements },
    },
  };
  const json = JSON.stringify(elm);
  const info = parseElmDefines(json);
  if (!info) throw new Error(`fixture ${name} did not parse`);
  return { info, elm: JSON.parse(json), source: lines.join("\n") };
}

/** A measure whose Numerator runs through a one-parameter function, plus a two-declaration overload
 *  group — the two shapes a body-only rendering cannot describe. */
function measure(): SpecLibraryInput {
  return library("Doc", [
    { name: "Initial Population", body: "true", expression: literal("true") },
    { name: "Denominator", body: '"Initial Population"', expression: ref("Initial Population") },
    { name: "Numerator", body: '"ToUnit"(\'mm[Hg]\') is not null', expression: ref("ToUnit") },
    { name: "ToUnit", body: '"Unit Label"', operands: { unit: "String" }, expression: ref("Unit Label") },
    { name: "Unit Label", body: "true", expression: literal("true") },
    // One name, two declarations — an overload group, as FHIRHelpers declares `ToString`.
    { name: "ToString", body: "value", operands: { value: "String" }, expression: literal("true") },
    { name: "ToString", body: "ToString(value)", operands: { value: "Integer" }, expression: literal("true") },
  ]);
}

